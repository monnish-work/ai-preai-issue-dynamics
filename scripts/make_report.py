"""
make_report.py - writes docs/RESULTS.md (current main results) from the result tables, so the report always
matches the data. Usage:  python scripts/make_report.py <paired_tag> <whole_history_tag>
                          e.g. python scripts/make_report.py ext_paired ext
"""
import sys
from datetime import date
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
TP, TW = (sys.argv[1], sys.argv[2]) if len(sys.argv) > 2 else ("ext_paired", "ext")
RP, RW = ROOT / f"results_{TP}" / "v2", ROOT / f"results_{TW}" / "v2"
study = pd.concat([pd.read_csv(f) for f in sorted((ROOT / "data").glob("study_repos_phase*.csv"))])
if "tier" not in study.columns:
    study["tier"] = "S"
study["tier"] = study.tier.fillna("S")
TIER = {"S": "strict", "R1": "30–59 commits", "R2": "< 2 % declared files"}
win = pd.read_csv(ROOT / "data" / "ai_declaration_windows.csv")
RM_W = pd.read_csv(RW / "repo_measures.csv")
analysed = set(RM_W.repo)
pairs = study[study.repo.isin(analysed)].copy()
pairs["k"] = pairs.match_id.str[1:].astype(int)
n_pairs = pairs.match_id.nunique()
RM_P = pd.read_csv(RP / "repo_measures.csv")
n_paired = RM_P.pair.nunique()


def f(x, d=2):
    if pd.isna(x) or x == "":
        return "–"
    x = float(x)
    return f"{x:,.{d}f}"


def p(x):
    if pd.isna(x) or x == "":
        return "–"
    return "< 0.001" if float(x) < 0.001 else f"{float(x):.3f}"


L = []
L.append(f"# Results ({n_pairs} matched pairs)\n")
L.append(f"Generated by `scripts/make_report.py {TP} {TW}` on {date.today().isoformat()} from `results_{TP}/v2/` (main result: "
         f"AI-declaration windows, {n_paired} pairs) and `results_{TW}/v2/` (whole history, {n_pairs} pairs). Definitions: "
         f"[ANALYSIS.md](ANALYSIS.md), section 1. Dataset: [DATASET.md](DATASET.md).\n")

# ---------------------------------------------------------------- dataset
L.append("## 1. Analysed pairs\n")
L.append("Selection rule: *strict* = at least 60 non-merge commits and at least 2 % of `.py` files declared (≥ 2 files); "
         "relaxed pairs (added to reach 40 pairs) have 30–59 commits or fewer than 2 % declared files. Section 9 repeats the main tests on the strict pairs only.\n")
L.append("| Pair | AI-declared repository | Pre-AI partner | Rule | Python KLOC at last commit (AI / Pre-AI) | Analysed commits in AI window |")
L.append("|---|---|---|---|---:|---:|")
kl = RM_W.set_index("repo").last_kloc
w = win.set_index("repo").commits_in_window
for _, g in pairs.sort_values("k").groupby("k", sort=True):
    a = g[g.group == "AI"].repo.iloc[0]; b = g[g.group == "PreAI"].repo.iloc[0]
    inc = "" if a in set(RM_P.repo) else " (too short: whole history only)"
    L.append(f"| {g.match_id.iloc[0]} | [{a}](https://github.com/{a}) | [{b}](https://github.com/{b}) | {TIER.get(g.tier.iloc[0], g.tier.iloc[0])} | {f(kl.get(a), 1)} / {f(kl.get(b), 1)} | {w.get(a, '–')}{inc} |")
L.append("")

# ---------------------------------------------------------------- repo-level tests
names = {"intro_per_kloc": "Introduced per KLOC", "removed_per_kloc": "Removed per KLOC",
         "intro_per_kloc_per_commit": "Introduced per KLOC per commit", "removed_per_kloc_per_commit": "Removed per KLOC per commit",
         "density_last": "Density at last commit", "density_mean": "Mean density", "removed_share": "Share of introduced issues removed",
         "median_life_commits": "Median lifetime (commits)"}
for tag, R, title in ((TP, RP, f"AI-declaration windows ({n_paired} pairs, main result)"), (TW, RW, f"whole history ({n_pairs} pairs)")):
    T = pd.read_csv(R / "repo_tests.csv")
    L.append(f"## {'2' if tag == TP else '3'}. Repository level: {title}\n")
    L.append("Two-sided Mann–Whitney U (exact distribution), Cliff's δ (> 0: higher in AI-declared), "
             f"Holm correction over all {T.p.notna().sum()} tests of the table (5 categories × 8 measures). All four attributes together:\n")
    L.append("| Measure | AI-declared median | Pre-AI median | p | p (Holm) | Cliff's δ |")
    L.append("|---|---:|---:|---:|---:|---:|")
    for _, t in T[T.category == "all"].iterrows():
        L.append(f"| {names[t.measure]} | {f(t.AI_declared_median)} | {f(t.PreAI_median)} | {p(t.p)} | {p(t.p_holm)} | {f(t.cliffs_delta)} |")
    s = T.sort_values("p").head(3)
    L.append("\nSmallest p-values over all categories: " + "; ".join(
        f"{r.category} {names[r.measure].lower()} (p = {p(r.p)}, Holm {p(r.p_holm)}, δ = {f(r.cliffs_delta)})" for _, r in s.iterrows())
        + f". Tests significant after Holm: **{int((T.p_holm < 0.05).sum())}**.\n")

# ---------------------------------------------------------------- pooled survival
L.append("## 4. Pooled survival (supporting evidence)\n")
L.append("| Window | Category | AI-declared issues | Pre-AI issues | KM median AI / Pre-AI (commits) | Log-rank p | Pair-stratified p |")
L.append("|---|---|---:|---:|---|---:|---:|")
for lab, R in (("AI-declaration windows", RP), ("Whole history", RW)):
    P = pd.read_csv(R / "pooled_tests.csv")
    for _, t in P[P.unit == "commits"].iterrows():
        L.append(f"| {lab} | {t.category} | {int(t.n_AI_declared)} | {int(t.n_PreAI)} | {f(t.AI_declared_km_median, 0)} / {f(t.PreAI_km_median, 0)} | {p(t.logrank_p)} | {p(t.pair_stratified_p)} |")
L.append("\n'–' as median: fewer than half of the issues were removed within the window.\n")

# ---------------------------------------------------------------- mechanisms
L.append("## 5. How issues disappear\n")
L.append("| Window | Group | code_changed | file_deleted | code_still_present | Removals |")
L.append("|---|---|---:|---:|---:|---:|")
for lab, R in (("AI-declaration windows", RP), ("Whole history", RW)):
    M = pd.read_csv(R / "mechanism_shares.csv", header=[0, 1], index_col=0)
    for g in M.index:
        c = M.loc[g, "count"]; sh = M.loc[g, "share"]
        L.append(f"| {lab} | {g} | {f(100 * sh['code_changed'], 0)} % | {f(100 * sh['file_deleted'], 0)} % | {f(100 * sh['code_still_present'], 0)} % | {int(c.sum())} |")
L.append("")

# ---------------------------------------------------------------- process metrics
L.append("## 6. Process metrics\n")
L.append("| Window | Measure | AI-declared median | Pre-AI median | p | p (Holm) | Cliff's δ |")
L.append("|---|---|---:|---:|---:|---:|---:|")
for lab, R in (("AI-declaration windows", RP), ("Whole history", RW)):
    for _, t in pd.read_csv(R / "process_tests.csv").iterrows():
        L.append(f"| {lab} | {t.measure} | {f(t.AI_declared_median)} | {f(t.PreAI_median)} | {p(t.p)} | {p(t.p_holm)} | {f(t.cliffs_delta)} |")
L.append("")

# ---------------------------------------------------------------- densities
L.append("## 7. Density per KLOC per repository and attribute (last analysed commit)\n")
L.append("| Pair | Repository | Group | Maint. | Rel. | Sec. | Perf. | All |")
L.append("|---|---|---|---:|---:|---:|---:|---:|")
R2 = RM_W.copy(); R2["k"] = R2.pair.str[1:].astype(int)
for _, r in R2.sort_values(["k", "group"]).iterrows():
    L.append(f"| {r.pair} | {r.repo} | {r.group} | {f(r.maintainability_density_last)} | {f(r.reliability_density_last)} | "
             f"{f(r.security_density_last)} | {f(r.performance_density_last)} | {f(r.all_density_last)} |")
L.append("")
c = pd.read_csv(RP / "count_reconciliation.csv")
L.append("## 8. How the counts fit together (AI-declaration windows)\n")
L.append("| Set | Histories | Removed |\n|---|---:|---:|")
for _, r in c.iterrows():
    L.append(f"| {r.set.strip()} | {r.histories:,} | {r.removed:,} |")
L.append("")
L.append("## 9. Sensitivity analyses\n")
L.append("| Analysis | Window | Smallest p | Tests significant after Holm | Introduced per KLOC, AI / Pre-AI median (p) |")
L.append("|---|---|---:|---:|---|")
for lab, sub in (("Strict-rule pairs only", "v2_sens_strict_tier"), ("Replication-package mapping (multi-quality rules dropped)", "v2_sens_strict_mapping"),
                 ("Non-blank lines as KLOC", "v2_sens_nonblank_loc")):
    for wl, tag in (("AI-declaration windows", TP), ("Whole history", TW)):
        fp = ROOT / f"results_{tag}" / sub / "repo_tests.csv"
        if fp.exists():
            T = pd.read_csv(fp); r = T[(T.category == "all") & (T.measure == "intro_per_kloc")].iloc[0]
            L.append(f"| {lab} | {wl} | {p(T.p.min())} | {int((T.p_holm < 0.05).sum())} | {f(r.AI_declared_median)} / {f(r.PreAI_median)} ({p(r.p)}) |")
(ROOT / "docs" / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote docs/RESULTS.md", n_pairs, "pairs")

# ---------------------------------------------------------------- README summary (between markers)
TPt = pd.read_csv(RP / "repo_tests.csv"); TWt = pd.read_csv(RW / "repo_tests.csv")
row = lambda T, m: T[(T.category == "all") & (T.measure == m)].iloc[0]
Pw = pd.read_csv(RW / "pooled_tests.csv"); Pp = pd.read_csv(RP / "pooled_tests.csv")
pw = Pw[(Pw.unit == "commits") & (Pw.category == "all")].iloc[0]; pp = Pp[(Pp.unit == "commits") & (Pp.category == "all")].iloc[0]
Mw = pd.read_csv(RW / "mechanism_shares.csv", header=[0, 1], index_col=0)
fd = lambda g: 100 * Mw.loc[g, "share"]["file_deleted"]
PT = pd.read_csv(RW / "process_tests.csv").set_index("measure")
n_strict = int((pairs[pairs.group == "AI"].tier == "S").sum())
R = [f"## Main results ({n_pairs} AI-declared + {n_pairs} Pre-AI repositories)\n",
     f"Full tables: [`docs/RESULTS.md`](docs/RESULTS.md) (generated from the result files). {n_strict} pairs meet the strict selection rule; "
     f"the others were added with relaxed rules and are marked (every test is repeated on the strict pairs only).\n",
     f"Repository level, all four attributes, AI-declaration windows ({n_paired} pairs):\n",
     "| Measure | AI-declared median | Pre-AI median | p | p (Holm) | Cliff's δ |", "|---|---:|---:|---:|---:|---:|"]
for m in ("intro_per_kloc", "removed_per_kloc", "density_last", "removed_share"):
    t = row(TPt, m)
    R.append(f"| {names[m]} | {f(t.AI_declared_median)} | {f(t.PreAI_median)} | {p(t.p)} | {p(t.p_holm)} | {f(t.cliffs_delta)} |")
nsig = int((TPt.p_holm < 0.05).sum() + (TWt.p_holm < 0.05).sum())
R += ["",
      f"- **Repository level (main result):** {nsig} of {int(TPt.p.notna().sum() + TWt.p.notna().sum())} repository-level tests are significant after Holm correction "
      f"(both windows). Introductions per KLOC: AI-declared {f(row(TWt, 'intro_per_kloc').AI_declared_median)} vs Pre-AI {f(row(TWt, 'intro_per_kloc').PreAI_median)} over the whole history (δ = {f(row(TWt, 'intro_per_kloc').cliffs_delta)}).",
      f"- **Survival (supporting):** pooled over all introduced issues, log-rank p = {p(pw.logrank_p)} (whole history) and {p(pp.logrank_p)} (AI windows); "
      f"stratified by matched pair p = {p(pw.pair_stratified_p)} and {p(pp.pair_stratified_p)}. Kaplan–Meier median {f(pw.AI_declared_km_median, 0)} vs {f(pw.PreAI_km_median, 0)} analysed commits (whole history).",
      f"- **How issues disappear:** {f(fd('AI-declared'), 0)} % of removals in AI-declared repositories are whole-file deletions, against {f(fd('Pre-AI'), 0)} % in Pre-AI repositories (whole history).",
      f"- **Process metrics:** developer experience (days since an author's first commit, per author) {f(PT.loc['dev_experience_author_days'].AI_declared_median, 0)} vs {f(PT.loc['dev_experience_author_days'].PreAI_median, 0)} days (p = {p(PT.loc['dev_experience_author_days'].p)}, Holm {p(PT.loc['dev_experience_author_days'].p_holm)}).",
      "- **Security** issues remain rare, so RQ3 has low power.", ""]
rd = (ROOT / "README.md").read_text(encoding="utf-8")
a, b = rd.index("<!-- RESULTS-START -->") + len("<!-- RESULTS-START -->"), rd.index("<!-- RESULTS-END -->")
(ROOT / "README.md").write_text(rd[:a] + "\n" + "\n".join(R) + "\n" + rd[b:], encoding="utf-8")
print("README results updated")
