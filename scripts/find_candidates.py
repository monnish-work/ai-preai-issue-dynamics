"""
find_candidates.py  -  Step 1 of the study: build an auditable candidate list.

Produces (in data/candidates/):
  ai_declaration_hits.csv   one row per search hit (repo, file, phrase, matched text)
  ai_candidate_repos.csv    one row per AI candidate repo, with metadata + %files declared
  preai_candidate_repos.csv one row per PreAI candidate repo (development ended < 2022)
  search_log.json           exact queries, dates and counts (for the methods section)

Needs a GitHub token in the environment variable GITHUB_TOKEN
(GitHub code search does not work without login).
"""
import csv, json, os, re, sys, time
from datetime import datetime, timezone
from pathlib import Path
import requests

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "candidates"
OUT.mkdir(parents=True, exist_ok=True)

TOKEN = os.environ.get("GITHUB_TOKEN", "").strip()
if not TOKEN:
    sys.exit("GITHUB_TOKEN is not set. Create a GitHub token and set $env:GITHUB_TOKEN first.")

S = requests.Session()
S.headers.update({
    "Authorization": f"Bearer {TOKEN}",
    "Accept": "application/vnd.github.text-match+json",
    "X-GitHub-Api-Version": "2022-11-28",
    "User-Agent": "ai-preai-issue-dynamics-study",
})

# Explicit attribution phrases (brief section 4, step 7)
AI_PHRASES = [
    "generated by ChatGPT", "generated with ChatGPT", "generated using ChatGPT", "written by ChatGPT",
    "generated by GitHub Copilot", "generated by Copilot", "generated with Copilot", "written by Copilot",
    "generated by Claude", "generated with Claude", "written by Claude",
    "generated by GPT-4", "generated with GPT-4",
    "generated with Cursor", "generated by Cursor",
]
EXCLUDE_WORDS = re.compile(
    r"tutorial|homework|assignment|course|exercise|lesson|leetcode|awesome|"
    r"benchmark|dataset|example|demo|template|boilerplate|playground|practice|learn|bootcamp",
    re.I)

log = {"run_started": datetime.now(timezone.utc).isoformat(), "queries": []}


def gh(url, params=None, kind="core"):
    """GET with polite rate limiting and retry on secondary limits."""
    for attempt in range(6):
        r = S.get(url, params=params, timeout=60)
        if r.status_code == 200:
            # code search: 10 req/min; repo search: 30 req/min
            time.sleep(6.5 if kind == "code" else 2.1 if kind == "search" else 0.1)
            return r.json()
        if r.status_code in (403, 429):
            wait = int(r.headers.get("Retry-After", "0") or 0)
            if not wait and r.headers.get("X-RateLimit-Remaining") == "0":
                wait = max(5, int(r.headers.get("X-RateLimit-Reset", time.time())) - int(time.time()) + 2)
            wait = wait or 60
            print(f"   rate limited, waiting {wait}s ...")
            time.sleep(wait)
            continue
        if r.status_code in (404, 409, 422, 451):
            return None
        print(f"   HTTP {r.status_code} for {url}: {r.text[:200]}")
        time.sleep(5)
    return None


# ---------------------------------------------------------------- AI hits
def search_ai_hits(max_pages=3):
    hits = []
    for phrase in AI_PHRASES:
        q = f'"{phrase}" language:Python'
        n_q = 0
        for page in range(1, max_pages + 1):
            d = gh("https://api.github.com/search/code",
                   {"q": q, "per_page": 100, "page": page}, kind="code")
            if not d or not d.get("items"):
                break
            for it in d["items"]:
                frags = " | ".join(m.get("fragment", "").replace("\n", " ")[:300]
                                   for m in it.get("text_matches", []))
                hits.append({
                    "repo": it["repository"]["full_name"],
                    "path": it["path"],
                    "phrase": phrase,
                    "matched_text": frags,
                    "file_url": it["html_url"],
                })
            n_q += len(d["items"])
            if len(d["items"]) < 100:
                break
        log["queries"].append({"type": "code", "q": q, "hits": n_q})
        print(f"  {phrase!r:40} {n_q} hits")
    return hits


def repo_meta(full):
    d = gh(f"https://api.github.com/repos/{full}")
    if not d:
        return None
    return {
        "repo": full, "url": d["html_url"], "stars": d["stargazers_count"], "forks": d["forks_count"],
        "size_kb": d["size"], "fork": d["fork"], "archived": d["archived"],
        "created_at": d["created_at"][:10], "pushed_at": d["pushed_at"][:10],
        "default_branch": d["default_branch"], "description": (d.get("description") or "")[:200],
        "language": d.get("language"),
    }


def count_py_files(full, branch):
    d = gh(f"https://api.github.com/repos/{full}/git/trees/{branch}", {"recursive": "1"})
    if not d:
        return None
    return sum(1 for t in d.get("tree", []) if t["type"] == "blob" and t["path"].endswith(".py"))


def build_ai_repos(hits):
    by_repo = {}
    for h in hits:
        by_repo.setdefault(h["repo"], set()).add(h["path"])
    rows = []
    print(f"\nChecking {len(by_repo)} AI candidate repos ...")
    for i, (full, files) in enumerate(sorted(by_repo.items(), key=lambda x: -len(x[1]))):
        m = repo_meta(full)
        if not m or m["fork"] or m["archived"] or m["language"] != "Python":
            continue
        if EXCLUDE_WORDS.search(full + " " + m["description"]):
            continue
        npy = count_py_files(full, m["default_branch"]) or 0
        m.update({
            "py_files": npy,
            "declared_files_found": len(files),
            "pct_declared": round(100 * len(files) / npy, 1) if npy else None,
            "meets_2pct_rule": bool(npy and len(files) / npy >= 0.02 and len(files) >= 2),
        })
        rows.append(m)
        if (i + 1) % 20 == 0:
            print(f"   {i+1}/{len(by_repo)}")
    return rows


# ---------------------------------------------------------------- PreAI
def search_preai(max_pages=5):
    q = ("language:Python fork:false archived:false stars:10..500 size:200..20000 "
         "created:2015-01-01..2020-12-31 pushed:<2022-01-01")
    rows = []
    for page in range(1, max_pages + 1):
        d = gh("https://api.github.com/search/repositories",
               {"q": q, "per_page": 100, "page": page, "sort": "stars", "order": "desc"}, kind="search")
        if not d or not d.get("items"):
            break
        for it in d["items"]:
            desc = it.get("description") or ""
            if EXCLUDE_WORDS.search(it["full_name"] + " " + desc):
                continue
            rows.append({
                "repo": it["full_name"], "url": it["html_url"], "stars": it["stargazers_count"],
                "forks": it["forks_count"], "size_kb": it["size"], "created_at": it["created_at"][:10],
                "pushed_at": it["pushed_at"][:10], "default_branch": it["default_branch"],
                "description": desc[:200],
            })
    log["queries"].append({"type": "repositories", "q": q, "kept": len(rows)})
    return rows


def write_csv(path, rows):
    if not rows:
        print(f"   (no rows for {path.name})"); return
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader(); w.writerows(rows)
    print(f"   wrote {path.relative_to(ROOT)}  ({len(rows)} rows)")


if __name__ == "__main__":
    me = gh("https://api.github.com/user")
    print(f"Logged in to GitHub as: {me and me.get('login')}")
    print("\n[1/3] Searching Python code for explicit AI-attribution phrases (takes ~5-8 min) ...")
    hits = search_ai_hits()
    write_csv(OUT / "ai_declaration_hits.csv", hits)

    print("\n[2/3] Collecting AI candidate repo metadata ...")
    ai = build_ai_repos(hits)
    ai.sort(key=lambda r: (not r["meets_2pct_rule"], -r["declared_files_found"]))
    write_csv(OUT / "ai_candidate_repos.csv", ai)

    print("\n[3/3] Searching PreAI repositories (last push before 2022) ...")
    pre = search_preai()
    write_csv(OUT / "preai_candidate_repos.csv", pre)

    log["run_finished"] = datetime.now(timezone.utc).isoformat()
    (OUT / "search_log.json").write_text(json.dumps(log, indent=2))
    n_ok = sum(r["meets_2pct_rule"] for r in ai)
    print(f"\nDONE. AI repos meeting the 2% rule: {n_ok}.  PreAI candidates: {len(pre)}.")
    print("Candidate lists written to data\\candidates.")
