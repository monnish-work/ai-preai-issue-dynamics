"""
find_candidates_wide.py - wider search for AI-declared Python repositories (dataset extension towards 83 pairs).

Why a wider search: the first search (find_candidates.py) used 15 phrases and at most 300 results per phrase.
GitHub code search returns at most 1,000 results per query, so this script
  1. uses more declaration phrases (same rule: an explicit statement that an AI tool generated/wrote code),
  2. splits every phrase query into file-size slices (`size:` qualifier), so each slice stays under the cap,
  3. reads up to 10 pages per slice,
  4. also searches commit messages for AI co-author / generated-with trailers, sliced by month
     (evidence type "commit", reported separately: it is a different kind of declaration),
  5. pre-classifies every repository automatically, so manual checking starts with the strongest ones:
       A  >= 2 declared .py files, >= 2 % of .py files, >= 60 non-merge commits  -> check by hand first
       B  meets the declaration rule, 30-59 commits (usable with fewer sampled commits)
       C  commit-message evidence only, or < 2 declared files
       X  rejected by a hard filter (fork, archived, not Python, tutorial/homework/..., < 30 commits)

Needs a GitHub token in the environment variable GITHUB_TOKEN (never write it into a file).
Run on the laptop with run_wide_search.ps1, which asks for the token and keeps it in memory only.

Output (data/candidates/wide/): hits_code.csv, hits_commits.csv, ai_candidates_wide.csv, search_log_wide.json
Resumable: finished queries are cached in data/candidates/wide/cache/ and skipped on a re-run.
Usage: python scripts/find_candidates_wide.py [--dry-run] [--max-pages 10] [--skip-commits]
"""
import argparse, csv, hashlib, json, os, re, sys, time
from datetime import date, datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "candidates" / "wide"
CACHE = OUT / "cache"
ap = argparse.ArgumentParser()
ap.add_argument("--dry-run", action="store_true", help="print the queries only, no network")
ap.add_argument("--max-pages", type=int, default=10)
ap.add_argument("--skip-commits", action="store_true")
ap.add_argument("--max-commit-repos", type=int, default=1500,
                help="commit-message evidence finds repos in every language; check at most this many of them")
A = ap.parse_args()

PHRASES = [  # first-search phrases + new ones (all explicit generation/authorship statements)
    "generated by ChatGPT", "generated with ChatGPT", "generated using ChatGPT", "written by ChatGPT",
    "written with ChatGPT", "created by ChatGPT", "created with ChatGPT", "code from ChatGPT",
    "generated by GitHub Copilot", "generated by Copilot", "generated with Copilot", "written by Copilot",
    "generated with GitHub Copilot", "written with Copilot",
    "generated by Claude", "generated with Claude", "written by Claude", "written with Claude",
    "generated by Claude Code", "generated with Claude Code", "created by Claude",
    "generated by GPT-4", "generated with GPT-4", "generated by GPT-4o", "generated by GPT-3.5",
    "generated by OpenAI", "generated with OpenAI Codex", "generated by Codex", "written by Codex",
    "generated with Cursor", "generated by Cursor",
    "generated by Gemini", "generated with Gemini", "written by Gemini",
    "AI-generated code", "this code was generated by AI", "generated by an LLM", "generated with an LLM",
    "generated by a large language model", "LLM-generated",
]
SIZE_SLICES = ["<2000", "2000..5000", "5000..10000", "10000..20000", "20000..50000", ">50000"]
COMMIT_PHRASES = ['"Co-Authored-By: Claude"', '"Generated with Claude Code"', '"Co-authored-by: Copilot"',
                  '"Co-authored-by: Cursor"', '"generated by ChatGPT"', '"Co-authored-by: Codex"']
EXCLUDE_WORDS = re.compile(r"tutorial|homework|assignment|course|exercise|lesson|leetcode|awesome|benchmark|"
                           r"dataset|example|demo|template|boilerplate|playground|practice|learn|bootcamp", re.I)


def months(start=date(2022, 12, 1), end=None):
    end = end or date.today()
    d = start
    while d <= end:
        n = date(d.year + (d.month == 12), d.month % 12 + 1, 1)
        yield f"{d.isoformat()}..{date.fromordinal(n.toordinal() - 1).isoformat()}"
        d = n


if A.dry_run:
    n = 0
    for p in PHRASES:
        for s in SIZE_SLICES:
            print(f'code   : "{p}" language:Python size:{s}'); n += 1
    if not A.skip_commits:
        for p in COMMIT_PHRASES:
            for m in months():
                n += 1
        print(f"commits: {len(COMMIT_PHRASES)} phrases x {len(list(months()))} months (e.g. {COMMIT_PHRASES[0]} author-date:{next(months())})")
    print(f"{n} queries; at about 7 s per page (GitHub limit: 10 code searches/min) budget 2-6 hours.")
    sys.exit(0)

import requests  # noqa: E402

TOKEN = os.environ.get("GITHUB_TOKEN", "").strip()
if not TOKEN:
    sys.exit("GITHUB_TOKEN is not set. Use run_wide_search.ps1, which asks for it without saving it.")
S = requests.Session()
S.headers.update({"Authorization": f"Bearer {TOKEN}", "Accept": "application/vnd.github.text-match+json",
                  "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "ai-preai-issue-dynamics-study"})
OUT.mkdir(parents=True, exist_ok=True); CACHE.mkdir(exist_ok=True)
log = {"run_started": datetime.now(timezone.utc).isoformat(), "queries": []}


def gh(url, params=None, kind="core", headers=None):
    for _ in range(8):
        try:
            r = S.get(url, params=params, timeout=60, headers=headers)
        except requests.RequestException as e:
            print("   network error:", e); time.sleep(20); continue
        if r.status_code == 200:
            time.sleep(6.5 if kind == "code" else 2.1 if kind == "search" else 0.05)
            return r
        if r.status_code in (403, 429):
            wait = int(r.headers.get("Retry-After", "0") or 0)
            if not wait and r.headers.get("X-RateLimit-Remaining") == "0":
                wait = max(5, int(r.headers.get("X-RateLimit-Reset", time.time())) - int(time.time()) + 2)
            print(f"   rate limited, waiting {wait or 60}s"); time.sleep(wait or 60); continue
        if r.status_code in (404, 409, 422, 451):
            return None
        print(f"   HTTP {r.status_code}: {r.text[:150]}"); time.sleep(5)
    return None


def search(endpoint, q, kind, extra_headers=None):
    """All pages of one query, cached on disk (resumable)."""
    f = CACHE / (hashlib.sha1((endpoint + q).encode()).hexdigest() + ".json")
    if f.exists():
        return json.loads(f.read_text(encoding="utf-8"))
    items, total = [], None
    for page in range(1, A.max_pages + 1):
        r = gh(f"https://api.github.com/search/{endpoint}", {"q": q, "per_page": 100, "page": page}, kind, extra_headers)
        if r is None:
            break
        d = r.json(); total = d.get("total_count", total)
        items += d.get("items", [])
        if len(d.get("items", [])) < 100:
            break
    f.write_text(json.dumps({"total": total, "items": items}), encoding="utf-8")
    log["queries"].append({"endpoint": endpoint, "q": q, "total_count": total, "retrieved": len(items)})
    if total and total > 1000:
        print(f"   NOTE: {total} results > 1,000 cap for: {q}")
    return {"total": total, "items": items}


def write_csv(path, rows):
    if not rows:
        return
    keys = list(dict.fromkeys(k for r in rows for k in r))
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=keys); w.writeheader(); w.writerows(rows)
    print(f"   wrote {path.relative_to(ROOT)} ({len(rows)} rows)")


# ------------------------------------------------------------------ 1. code hits
code_hits = []
print(f"[1/4] Code search: {len(PHRASES)} phrases x {len(SIZE_SLICES)} size slices")
for p in PHRASES:
    n = 0
    for s in SIZE_SLICES:
        res = search("code", f'"{p}" language:Python size:{s}', "code")
        for it in res["items"]:
            frag = " | ".join(m.get("fragment", "").replace("\n", " ")[:300] for m in it.get("text_matches", []))
            if p.lower() not in frag.lower():      # GitHub matches loosely; keep exact-phrase hits only
                continue
            code_hits.append({"repo": it["repository"]["full_name"], "path": it["path"], "phrase": p,
                              "matched_text": frag, "file_url": it["html_url"]})
            n += 1
    print(f"   {p!r:45} {n} exact hits")
code_hits = list({(h["repo"], h["path"]): h for h in code_hits}.values())
write_csv(OUT / "hits_code.csv", code_hits)

# ------------------------------------------------------------------ 2. commit hits
commit_hits = []
if not A.skip_commits:
    print(f"[2/4] Commit search: {len(COMMIT_PHRASES)} phrases x monthly slices")
    for p in COMMIT_PHRASES:
        n = 0
        for m in months():
            res = search("commits", f"{p} author-date:{m}", "search")
            for it in res["items"]:
                commit_hits.append({"repo": it["repository"]["full_name"], "sha": it["sha"][:10], "phrase": p.strip('"'),
                                    "date": it["commit"]["author"]["date"][:10],
                                    "message": it["commit"]["message"].splitlines()[0][:200]})
                n += 1
        print(f"   {p:35} {n} commits")
    write_csv(OUT / "hits_commits.csv", commit_hits)

# ------------------------------------------------------------------ 3. repository metadata + pre-classification
known = set()
for f in (ROOT / "data" / "candidates" / "ai_candidate_repos.csv",):
    if f.exists():
        known |= {r["repo"] for r in csv.DictReader(open(f, encoding="utf-8"))}
files_by_repo, commits_by_repo = {}, {}
for h in code_hits:
    files_by_repo.setdefault(h["repo"], set()).add(h["path"])
for h in commit_hits:
    commits_by_repo.setdefault(h["repo"], []).append(h)
commit_only = sorted(set(commits_by_repo) - set(files_by_repo), key=lambda r: -len(commits_by_repo[r]))
repos = sorted(files_by_repo, key=lambda r: -len(files_by_repo[r])) + commit_only[:A.max_commit_repos]
print(f"[3/4] Metadata for {len(repos)} repositories ({len(known & set(repos))} already in the first search)")


def commit_count(full, branch):
    r = gh(f"https://api.github.com/repos/{full}/commits", {"sha": branch, "per_page": 1})
    if r is None:
        return None
    m = re.search(r'page=(\d+)>; rel="last"', r.headers.get("Link", ""))
    return int(m.group(1)) if m else len(r.json())


rows = []
for i, full in enumerate(repos):
    r = gh(f"https://api.github.com/repos/{full}")
    if r is None:
        continue
    d = r.json()
    row = {"repo": full, "url": d["html_url"], "stars": d["stargazers_count"], "forks": d["forks_count"],
           "language": d.get("language"), "fork": d["fork"], "archived": d["archived"],
           "created_at": d["created_at"][:10], "pushed_at": d["pushed_at"][:10], "default_branch": d["default_branch"],
           "description": (d.get("description") or "")[:200], "in_first_search": full in known,
           "declared_files": len(files_by_repo.get(full, ())), "commit_declarations": len(commits_by_repo.get(full, [])),
           "first_commit_declaration": min((h["date"] for h in commits_by_repo.get(full, [])), default="")}
    reject = []
    if d["fork"]: reject.append("fork")
    if d["archived"]: reject.append("archived")
    if d.get("language") != "Python": reject.append("not Python")
    if EXCLUDE_WORDS.search(full + " " + row["description"]): reject.append("tutorial/demo keyword")
    npy = ncommits = None
    if not reject:
        t = gh(f"https://api.github.com/repos/{full}/git/trees/{d['default_branch']}", {"recursive": "1"})
        npy = sum(1 for x in t.json().get("tree", []) if x["type"] == "blob" and x["path"].endswith(".py")) if t else None
        ncommits = commit_count(full, d["default_branch"])
        if ncommits is not None and ncommits < 30: reject.append("< 30 commits")
    pct = round(100 * row["declared_files"] / npy, 1) if npy else None
    decl_ok = row["declared_files"] >= 2 and pct is not None and pct >= 2
    row.update({"py_files": npy, "pct_declared": pct, "commits_incl_merges": ncommits, "reject_reason": "; ".join(reject),
                "class": "X" if reject else "A" if decl_ok and (ncommits or 0) >= 60 else "B" if decl_ok else "C"})
    rows.append(row)
    if (i + 1) % 25 == 0:
        print(f"   {i + 1}/{len(repos)}")
rows.sort(key=lambda r: ("ABCX".index(r["class"]), -r["declared_files"], -(r["stars"] or 0)))
write_csv(OUT / "ai_candidates_wide.csv", rows)

# ------------------------------------------------------------------ 4. summary
log["run_finished"] = datetime.now(timezone.utc).isoformat()
summary = {c: sum(r["class"] == c for r in rows) for c in "ABCX"}
log["summary"] = summary
(OUT / "search_log_wide.json").write_text(json.dumps(log, indent=2), encoding="utf-8")
print(f"[4/4] DONE. Class A (check by hand first): {summary['A']}, B: {summary['B']}, C: {summary['C']}, rejected: {summary['X']}")
print("Open data\\candidates\\wide\\ai_candidates_wide.csv and validate class A by hand (DATASET.md, section 2).")
