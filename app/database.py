"""
database.py - builds app/study.db (SQLite) from the study's derived data and results.

    python app/database.py            # rebuild from data/derived*/ and results*/

Keeps the tables the app writes to (users, manual_checks) when rebuilding.
"""
import json
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DB = Path(__file__).resolve().parent / "study.db"

PRIMARY = {("sonarqube", "maintainability"), ("sonarqube", "reliability"), ("semgrep", "security")}

PHASES = {
    "pilot": {"label": "Pilot (1 + 1, last 30 commits)", "derived": "derived", "results": "results",
              "sampling": "Last 30 non-merge commits on the default branch"},
    "phaseC": {"label": "Main study (5 + 5, whole history)", "derived": "derived_phaseC", "results": "results_phaseC",
               "sampling": "30 non-merge commits evenly spaced over the whole history"},
}

INFO = {
    "pachterlab/edgePython": ("Python port of edgeR: statistics for gene-expression (RNA-seq) data.",
                              "44 of 49 .py files carry: “# This code was written by Claude (Anthropic). The project was directed by Lior Pachter.” Commit messages also credit Codex.",
                              "Claude", 94),
    "dhlab-epfl/dhSegment": ("Deep-learning framework for segmenting historical documents.",
                             "Last commit Dec 2020, before modern AI coding assistants.", "", 385),
    "TaylorResearchLab/scedar": ("Exploratory analysis library for single-cell RNA-seq data.",
                                 "Last commit Apr 2021.", "", 41),
    "binsync/declib": ("Library that puts many decompilers (reverse engineering) behind one API.",
                       "“Note to reader: most of this code was generated by Claude 4.5.” (decompiler_server.py, decompiler_client.py)",
                       "Claude", 190),
    "getavalon/core": ("Asset pipeline for film, animation and games studios.", "Last commit Jun 2021.", "", 221),
    "jaxleyverse/jaxley": ("Differentiable simulator of biophysical neuron models, built on JAX.",
                           "“This function was written by ChatGPT, based on the prompt: …” and “Written by ChatGPT.” (3 files)",
                           "ChatGPT", 212),
    "initc3/HoneyBadgerMPC": ("Multi-party computation layer that keeps blockchain data confidential.",
                              "Last commit Mar 2020.", "", 137),
    "temporalecologylab/TreeRings": ("Lab tooling to image and measure tree-ring cores.",
                                     "“# Generated with ChatGPT-4.0” (5 of 25 .py files)", "ChatGPT", 6),
    "hanyas/sds": ("Toolbox for inference and control of switching dynamical systems.", "Last commit Aug 2021.", "", 11),
    "mit-acl/tcaff": ("Robotics research code for aligning coordinate frames across robots.",
                      "“Written by ChatGPT and fixed by me” (2 files)", "ChatGPT", 21),
    "jsosa/LFPtools": ("Command-line tools that prepare LISFLOOD-FP flood simulations.", "Last commit Mar 2020.", "", 40),
}
MATCH = {"pachterlab/edgePython": "M1", "TaylorResearchLab/scedar": "M1", "binsync/declib": "M2",
         "getavalon/core": "M2", "jaxleyverse/jaxley": "M3", "initc3/HoneyBadgerMPC": "M3",
         "temporalecologylab/TreeRings": "M4", "hanyas/sds": "M4", "mit-acl/tcaff": "M5", "jsosa/LFPtools": "M5"}

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (name TEXT PRIMARY KEY, created TEXT, last_seen TEXT, visits INTEGER);
CREATE TABLE IF NOT EXISTS manual_checks (phase TEXT, issue_id INTEGER, intro TEXT, persist TEXT, removal TEXT,
    notes TEXT, checked_by TEXT, updated TEXT, PRIMARY KEY (phase, issue_id));
DROP TABLE IF EXISTS phases; DROP TABLE IF EXISTS projects; DROP TABLE IF EXISTS snapshots;
DROP TABLE IF EXISTS issues; DROP TABLE IF EXISTS tables_json;
CREATE TABLE phases (id TEXT PRIMARY KEY, label TEXT, sampling TEXT);
CREATE TABLE projects (phase TEXT, repo TEXT, grp TEXT, match_id TEXT, description TEXT, evidence TEXT,
    ai_tool TEXT, stars INTEGER, PRIMARY KEY (phase, repo));
CREATE TABLE snapshots (phase TEXT, repo TEXT, idx INTEGER, sha TEXT, date TEXT, loc INTEGER,
    maint INTEGER, rel INTEGER, sec INTEGER, missing TEXT, PRIMARY KEY (phase, repo, idx));
CREATE TABLE issues (phase TEXT, id INTEGER, repo TEXT, grp TEXT, tool TEXT, rule TEXT, category TEXT, severity TEXT,
    message TEXT, cwe TEXT, path_first TEXT, path_last TEXT, lines TEXT, paths TEXT, intro_idx INTEGER,
    last_idx INTEGER, removed_idx INTEGER, mechanism TEXT, baseline INTEGER, moved INTEGER,
    life_days REAL, life_commits INTEGER, PRIMARY KEY (phase, id));
CREATE INDEX IF NOT EXISTS ix_issues ON issues (phase, repo, category);
CREATE TABLE tables_json (phase TEXT, name TEXT, body TEXT, PRIMARY KEY (phase, name));
"""


def build():
    con = sqlite3.connect(DB)
    con.executescript(SCHEMA)
    for pid, ph in PHASES.items():
        D, R = ROOT / "data" / ph["derived"], ROOT / ph["results"]
        if not (D / "issue_histories.csv").exists():
            print("  skip", pid)
            continue
        con.execute("INSERT INTO phases VALUES (?,?,?)", (pid, ph["label"], ph["sampling"]))
        H = pd.read_csv(D / "issue_histories.csv", keep_default_na=False)
        S = pd.read_csv(D / "snapshots.csv", keep_default_na=False)
        F = pd.read_csv(D / "findings.csv", keep_default_na=False,
                        usecols=["repo", "snapshot", "issue_id", "tool", "category", "line", "path"])
        keep = lambda df: df[[(t, c) in PRIMARY for t, c in zip(df.tool, df.category)]]
        H, F = keep(H), keep(F)
        cnt = F.groupby(["repo", "snapshot", "category"]).size()
        for repo, grp in S.groupby("repo")["group"].first().items():
            d, ev, tool, stars = INFO.get(repo, ("", "", "", None))
            con.execute("INSERT INTO projects VALUES (?,?,?,?,?,?,?,?)",
                        (pid, repo, grp, MATCH.get(repo, "P1") if pid != "pilot" else "P1", d, ev, tool, stars))
        for _, r in S.iterrows():
            g = lambda c: int(cnt.get((r.repo, int(r["index"]), c), 0))
            con.execute("INSERT INTO snapshots VALUES (?,?,?,?,?,?,?,?,?,?)",
                        (pid, r.repo, int(r["index"]), r.commit, r.date, int(r.py_loc),
                         g("maintainability"), g("reliability"), g("security"), str(r.get("missing_tools", "")).strip()))
        per = F.sort_values("snapshot").groupby("issue_id")
        lines = per.line.apply(lambda x: json.dumps([[int(s), int(l)] for s, l in zip(F.loc[x.index, "snapshot"], x)]))
        paths = per.path.apply(lambda x: json.dumps(list(dict.fromkeys(x))))
        rows = []
        for _, x in H.iterrows():
            i = int(x.issue_id)
            rows.append((pid, i, x.repo, x.group, x.tool, x.rule, x.category, x.severity, x.message, x.cwe,
                         x.path_first, x.path_last, lines.get(i, "[]"), paths.get(i, "[]"),
                         int(x.introduced_snapshot), int(x.last_seen_snapshot),
                         int(x.removed_snapshot) if x.removed_snapshot != "" else None, x.removal_mechanism,
                         int(str(x.present_at_first_snapshot) == "True"), int(str(x.moved) == "True"),
                         float(x.lifetime_days), int(x.lifetime_snapshots)))
        con.executemany("INSERT INTO issues VALUES (" + ",".join("?" * 22) + ")", rows)
        for name in ["validation_sonar_agreement", "validation_match_methods", "manual_validation_sample",
                     "rates_by_repo", "repo_level_tests", "repo_level_measures", "logrank_tests",
                     "rq3_security_vs_other", "removal_mechanisms", "lifetime_summary",
                     "validation_event_agreement", "validation_disagreement_reasons"]:
            f = R / f"{name}.csv"
            if f.exists() and f.stat().st_size > 5:
                body = pd.read_csv(f, keep_default_na=False).to_json(orient="records")
                con.execute("INSERT INTO tables_json VALUES (?,?,?)", (pid, name, body))
        print(f"  {pid}: {S.repo.nunique()} projects, {len(rows)} issues")
    vfile = ROOT / "tool_versions.txt"
    if vfile.exists():
        v = vfile.read_text(encoding="utf-8-sig").splitlines()[:9]
        con.execute("INSERT INTO tables_json VALUES (?,?,?)", ("all", "versions", json.dumps(v)))
    con.commit()
    con.close()
    print("Built", DB)


if __name__ == "__main__":
    build()
